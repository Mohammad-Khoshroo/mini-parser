import org.antlr.v4.runtime.*;
import org.antlr.v4.runtime.tree.*;

public class parser {
    public static void main(String[] args) throws Exception {
        
        // Sample test strings (both valid and invalid syntax)
        String[] testStrings = {
            "x = 10 + 20 * 3;",
            "(a + b) / (c - 4);",
            "y = ;",                    // Intentionally invalid syntax for testing error reporting
            "total = x + 5 * (y - 2);"
        };

        for (String testStr : testStrings) {
            System.out.println("\n--- Parsing Input: \"" + testStr + "\" ---");
            
            // 1. Convert input string into ANTLR CharStream
            CharStream input = CharStreams.fromString(testStr);
            
            // 2. Feed the character stream into the lexer
            vrparserLexer lexer = new vrparserLexer(input);
            
            // 3. Create a buffer of tokens generated by the lexer
            CommonTokenStream tokens = new CommonTokenStream(lexer);
            
            // 4. Create the parser that consumes the token stream
            vrparserParser parser = new vrparserParser(tokens);
            
            // 5. Begin parsing from the entry rule 'program'
            ParseTree tree = parser.program();
            
            // 6. Display the textual parse tree (LISP-style S-expression)
            System.out.println("Parse Tree: " + tree.toStringTree(parser));
            
            // 7. Inspect syntax error count
            int errorCount = parser.getNumberOfSyntaxErrors();
            if (errorCount == 0) {
                System.out.println("Status: Parsing completed successfully (No syntax errors).");
            } else {
                System.out.println("Status: Parsing completed with " + errorCount + " syntax error(s).");
            }
        }
    }
}
